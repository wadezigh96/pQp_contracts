//! QPC Zcash wallet-adapter boundary.
//!
//! This crate deliberately does not parse Unified Addresses, hold keys, sign,
//! broadcast, or claim consensus verification. Those operations must be supplied
//! by a separately audited Zcash wallet backend implementing the traits below.
//! The default policy is shielded-only and fails closed.

use std::collections::HashSet;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ZcashNetwork {
    Mainnet,
    Testnet,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ReceiverKind {
    Orchard,
    Sapling,
    Transparent,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PrivacyPolicy {
    ShieldedOnly,
    AllowTransparentExplicitly,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ValidatedRecipient {
    /// Opaque reference generated by a trusted wallet backend; never the raw UA.
    pub opaque_ref: String,
    pub network: ZcashNetwork,
    pub receivers: Vec<ReceiverKind>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PaymentIntent {
    pub payment_id: String,
    pub source_chain: String,
    pub destination_network: ZcashNetwork,
    pub amount_zatoshis: u64,
    pub opaque_recipient_ref: String,
    pub nonce: u64,
    pub expires_at_unix: u64,
    pub privacy_policy: PrivacyPolicy,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PaymentState {
    Created,
    RecipientValidated,
    Authorized,
    BroadcastPending,
    Confirming,
    ReceiptVerified,
    Completed,
    Failed,
    PendingReconciliation,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum AdapterError {
    InvalidIntent,
    Expired,
    WrongNetwork,
    RecipientReferenceMismatch,
    NoPermittedShieldedReceiver,
    TransparentReceiverForbidden,
    InvalidTransition,
    Replay,
    BackendUnavailable,
}

pub trait UnifiedAddressValidator {
    /// Implement using a maintained Zcash address library. Must validate network
    /// and return receiver capabilities without exposing the raw address.
    fn validate_unified_address(
        &self,
        unified_address: &str,
        expected_network: ZcashNetwork,
    ) -> Result<ValidatedRecipient, AdapterError>;
}

pub trait ShieldedWalletBackend {
    /// Implementations must keep spending keys inside the wallet boundary.
    /// This interface intentionally does not expose key material to agents.
    fn prepare_shielded_payment(
        &self,
        intent: &PaymentIntent,
        recipient: &ValidatedRecipient,
    ) -> Result<String, AdapterError>;

    /// Return a wallet/chain observation identifier, not an assertion of finality.
    fn broadcast_signed_transaction(
        &self,
        signed_transaction_ref: &str,
    ) -> Result<String, AdapterError>;
}

#[derive(Default)]
pub struct ReplayGuard {
    seen: HashSet<(String, u64)>,
}

impl ReplayGuard {
    pub fn register(&mut self, source_chain: &str, nonce: u64) -> Result<(), AdapterError> {
        if !self.seen.insert((source_chain.to_owned(), nonce)) {
            return Err(AdapterError::Replay);
        }
        Ok(())
    }
}

pub fn validate_intent(
    intent: &PaymentIntent,
    recipient: &ValidatedRecipient,
    now_unix: u64,
) -> Result<(), AdapterError> {
    if intent.payment_id.is_empty()
        || intent.payment_id.len() > 128
        || intent.source_chain.is_empty()
        || intent.amount_zatoshis == 0
        || intent.opaque_recipient_ref.is_empty()
        || intent.expires_at_unix <= now_unix
    {
        return Err(if intent.expires_at_unix <= now_unix {
            AdapterError::Expired
        } else {
            AdapterError::InvalidIntent
        });
    }
    if recipient.network != intent.destination_network {
        return Err(AdapterError::WrongNetwork);
    }
    if recipient.opaque_ref != intent.opaque_recipient_ref {
        return Err(AdapterError::RecipientReferenceMismatch);
    }

    let has_shielded = recipient.receivers.iter().any(|r| {
        matches!(r, ReceiverKind::Orchard | ReceiverKind::Sapling)
    });
    if intent.privacy_policy == PrivacyPolicy::ShieldedOnly && !has_shielded {
        return Err(AdapterError::NoPermittedShieldedReceiver);
    }
    if intent.privacy_policy == PrivacyPolicy::ShieldedOnly
        && recipient.receivers.contains(&ReceiverKind::Transparent)
        && !has_shielded
    {
        return Err(AdapterError::TransparentReceiverForbidden);
    }
    Ok(())
}

pub fn transition(
    current: PaymentState,
    next: PaymentState,
) -> Result<PaymentState, AdapterError> {
    use PaymentState::*;
    let allowed = matches!(
        (current, next),
        (Created, RecipientValidated)
            | (RecipientValidated, Authorized)
            | (Authorized, BroadcastPending)
            | (BroadcastPending, Confirming)
            | (Confirming, ReceiptVerified)
            | (ReceiptVerified, Completed)
            | (BroadcastPending, PendingReconciliation)
            | (Confirming, PendingReconciliation)
            | (Created, Failed)
            | (RecipientValidated, Failed)
            | (Authorized, Failed)
            | (BroadcastPending, Failed)
            | (PendingReconciliation, Confirming)
    );
    if allowed { Ok(next) } else { Err(AdapterError::InvalidTransition) }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn intent() -> PaymentIntent {
        PaymentIntent {
            payment_id: "qpc-pay-001".into(),
            source_chain: "near:mainnet".into(),
            destination_network: ZcashNetwork::Testnet,
            amount_zatoshis: 50_000,
            opaque_recipient_ref: "opaque-recipient-01".into(),
            nonce: 7,
            expires_at_unix: 2_000,
            privacy_policy: PrivacyPolicy::ShieldedOnly,
        }
    }

    fn recipient(receivers: Vec<ReceiverKind>) -> ValidatedRecipient {
        ValidatedRecipient {
            opaque_ref: "opaque-recipient-01".into(),
            network: ZcashNetwork::Testnet,
            receivers,
        }
    }

    #[test]
    fn accepts_testnet_shielded_recipient() {
        assert_eq!(
            validate_intent(&intent(), &recipient(vec![ReceiverKind::Orchard]), 1_000),
            Ok(())
        );
    }

    #[test]
    fn rejects_transparent_only_recipient() {
        assert_eq!(
            validate_intent(&intent(), &recipient(vec![ReceiverKind::Transparent]), 1_000),
            Err(AdapterError::NoPermittedShieldedReceiver)
        );
    }

    #[test]
    fn rejects_wrong_network() {
        let mut r = recipient(vec![ReceiverKind::Orchard]);
        r.network = ZcashNetwork::Mainnet;
        assert_eq!(
            validate_intent(&intent(), &r, 1_000),
            Err(AdapterError::WrongNetwork)
        );
    }

    #[test]
    fn rejects_recipient_reference_substitution() {
        let mut r = recipient(vec![ReceiverKind::Orchard]);
        r.opaque_ref = "attacker-ref".into();
        assert_eq!(
            validate_intent(&intent(), &r, 1_000),
            Err(AdapterError::RecipientReferenceMismatch)
        );
    }

    #[test]
    fn rejects_expired_intent() {
        assert_eq!(
            validate_intent(&intent(), &recipient(vec![ReceiverKind::Orchard]), 2_000),
            Err(AdapterError::Expired)
        );
    }

    #[test]
    fn replay_guard_is_scoped_by_source_chain_and_nonce() {
        let mut guard = ReplayGuard::default();
        assert_eq!(guard.register("near:mainnet", 7), Ok(()));
        assert_eq!(guard.register("near:mainnet", 7), Err(AdapterError::Replay));
        assert_eq!(guard.register("zcash:testnet", 7), Ok(()));
    }

    #[test]
    fn lifecycle_requires_receipt_verification_before_completion() {
        assert_eq!(transition(PaymentState::Created, PaymentState::Completed),
            Err(AdapterError::InvalidTransition));
        assert_eq!(transition(PaymentState::Created, PaymentState::RecipientValidated),
            Ok(PaymentState::RecipientValidated));
        assert_eq!(transition(PaymentState::ReceiptVerified, PaymentState::Completed),
            Ok(PaymentState::Completed));
    }

    #[test]
    fn pending_reconciliation_can_resume_confirmation() {
        assert_eq!(
            transition(PaymentState::PendingReconciliation, PaymentState::Confirming),
            Ok(PaymentState::Confirming)
        );
    }
}
