    #[cfg(unix)]
    #[test]
    fn replay_records_are_owner_only() {
        use std::os::unix::fs::PermissionsExt;
        let temp = tempfile::tempdir().expect("temporary directory");
        let parent = private_test_directory(&temp, "private");
        let store = parent.join("replay-store");
        let guard = ReplayGuard::open(&store).unwrap();
        guard.register("near:mainnet", 11).unwrap();

        let directory_mode = std::fs::metadata(&store).unwrap().permissions().mode() & 0o777;
        assert_eq!(directory_mode, 0o700);
        let entry = std::fs::read_dir(&store).unwrap().next().unwrap().unwrap();
        let file_mode = entry.metadata().unwrap().permissions().mode() & 0o777;
        assert_eq!(file_mode, 0o600);
    }

