#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ZcashNetwork {
    Mainnet,
    Testnet,
    Regtest,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ReceiverKind {
    Orchard,
    Sapling,
    Transparent,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PrivacyPolicy {
    ShieldedOnly,
    AllowTransparentExplicitly,
}

/// A capability created only by the address validator.
///
/// The raw Unified Address is private and omitted from Debug output.
/// Agent-facing code should pass only `opaque_ref`.
#[derive(PartialEq, Eq)]
pub struct ValidatedRecipient {
    opaque_ref: String,
    network: ZcashNetwork,
    receivers: Vec<ReceiverKind>,
    #[allow(dead_code)] // Used by the future in-crate wallet transaction builder.
    raw_unified_address: String,
}

impl std::fmt::Debug for ValidatedRecipient {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ValidatedRecipient")
            .field("opaque_ref", &self.opaque_ref)
            .field("network", &self.network)
            .field("receivers", &self.receivers)
            .finish()
    }
}

impl ValidatedRecipient {
    pub fn opaque_ref(&self) -> &str {
        &self.opaque_ref
    }

    pub fn network(&self) -> ZcashNetwork {
        self.network
    }

    pub fn receiver_kinds(&self) -> &[ReceiverKind] {
        &self.receivers
    }

    /// Available only to wallet code in this crate; never expose to the agent.
    #[allow(dead_code)]
    pub(crate) fn raw_unified_address(&self) -> &str {
        &self.raw_unified_address
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PaymentIntent {
    pub payment_id: String,
    pub source_chain: String,
    pub destination_network: ZcashNetwork,
    pub amount_zatoshis: u64,
    pub opaque_recipient_ref: String,
    pub nonce: u64,
    pub expires_at_unix: u64,
    pub privacy_policy: PrivacyPolicy,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PaymentState {
    Created,
    RecipientValidated,
    Authorized,
    BroadcastPending,
    Confirming,
    ReceiptVerified,
    Completed,
    Failed,
    PendingReconciliation,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum AdapterError {
    InvalidIntent,
    Expired,
    WrongNetwork,
    RecipientReferenceMismatch,
    NoPermittedShieldedReceiver,
    TransparentReceiverForbidden,
    InvalidTransition,
    Replay,
    BackendUnavailable,
    InvalidUnifiedAddress,
    WrongAddressType,
    InvalidOpaqueReference,
    TransparentPolicyRequiresHumanAuthorization,
    InvalidReplayKey,
    ReplayStoreUnavailable,
}

pub trait UnifiedAddressValidator {
    /// Validate a ZIP-316 Unified Address and return receiver capabilities.
    /// The opaque reference is generated by the wallet boundary, not derived from
    /// or equal to the raw Unified Address.
    fn validate_unified_address(
        &self,
        unified_address: &str,
        expected_network: ZcashNetwork,
    ) -> Result<ValidatedRecipient, AdapterError>;
}

#[derive(Default)]
pub struct LibrustZcashAddressValidator;

struct UnifiedOnly(unified::Address);

impl TryFromAddress for UnifiedOnly {
    type Error = Infallible;

    fn try_from_unified(
        _network: NetworkType,
        address: unified::Address,
    ) -> Result<Self, ConversionError<Self::Error>> {
        Ok(Self(address))
    }
}

impl UnifiedAddressValidator for LibrustZcashAddressValidator {
    fn validate_unified_address(
        &self,
        unified_address: &str,
        expected_network: ZcashNetwork,
    ) -> Result<ValidatedRecipient, AdapterError> {
        let parsed: ZcashAddress = unified_address
            .parse()
            .map_err(|_| AdapterError::InvalidUnifiedAddress)?;

        let network = match expected_network {
            ZcashNetwork::Mainnet => NetworkType::Main,
            ZcashNetwork::Testnet => NetworkType::Test,
            ZcashNetwork::Regtest => NetworkType::Regtest,
        };
        let parsed = parsed
            .convert_if_network::<UnifiedOnly>(network)
            .map_err(|_| AdapterError::WrongNetwork)?;

        let mut receivers = Vec::new();
        if parsed
            .0
            .has_receiver_of_type(PoolType::Shielded(ShieldedPool::Orchard))
        {
            receivers.push(ReceiverKind::Orchard);
        }
        if parsed
            .0
            .has_receiver_of_type(PoolType::Shielded(ShieldedPool::Sapling))
        {
            receivers.push(ReceiverKind::Sapling);
        }
        if parsed.0.has_receiver_of_type(PoolType::Transparent) {
            receivers.push(ReceiverKind::Transparent);
        }
        if !receivers
            .iter()
            .any(|kind| matches!(kind, ReceiverKind::Orchard | ReceiverKind::Sapling))
        {
            return Err(if receivers.contains(&ReceiverKind::Transparent) {
                AdapterError::TransparentReceiverForbidden
            } else {
                AdapterError::NoPermittedShieldedReceiver
            });
        }

        // The opaque handle is generated here, never supplied by an agent.
        // The raw Unified Address stays inside this capability.
        let mut random = [0u8; 32];
        let mut rng = OsRng;
        rng.try_fill_bytes(&mut random)
            .map_err(|_| AdapterError::BackendUnavailable)?;
        let opaque_ref = format!("qpc-ua-v1:{}", encode_hex(&random));

        Ok(ValidatedRecipient {
            opaque_ref,
            network: expected_network,
            receivers,
            raw_unified_address: unified_address.to_owned(),
        })
    }
}

fn encode_hex(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut output = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        output.push(HEX[(byte >> 4) as usize] as char);
        output.push(HEX[(byte & 0x0f) as usize] as char);
    }
    output
}

